// Неразрывные пробелы при выводе текста: короткие слова, тире, числа
import { expect, test } from '@playwright/test';
import { t, typo } from '../../src/engine/html';

const show = (s: string) => typo(s).replace(/ /g, '·');

test('короткие слова, тире и числа не отрываются', () => {
  expect(show('Дом в лесу и на реке')).toBe('Дом в·лесу и·на·реке');
  expect(show('Для всех без исключения')).toBe('Для·всех без·исключения');
  expect(show('Быстро — и надёжно')).toBe('Быстро·— и·надёжно');
  expect(show('Пакетов 17 234 за 5 км')).toBe('Пакетов 17·234 за·5·км');
  expect(show('Пакетов 17 234 пришло')).toBe('Пакетов 17·234 пришло');
  expect(show('Рост 18 %')).toBe('Рост 18·%');
  // Длинные слова не трогаются, число от обычного слова не склеивается
  expect(show('Выручка 2024 выросла')).toBe('Выручка 2024 выросла');
  expect(show('Выручка 3 млн')).toBe('Выручка 3·млн');
  expect(show('Слайды как данные')).toBe('Слайды как данные');
});

test('разметка и адреса ссылок не ломаются', () => {
  expect(t('**В** доме и [в сети](https://a.ru/i_v)')).toContain('href="https://a.ru/i_v"');
  expect(t('{accent|в доме}')).toContain('в доме');
  expect(t('Формула {{a * 2}} и всё')).toContain('{{a * 2}}');
});
